import {
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { CelebrationsRepository } from './celebrations.repository';
import { AuditService } from '../../audit/audit.service';
import { AuditAction } from '@zentra/shared-types';
import { PrismaService } from '../../prisma/prisma.service';

@Injectable()
export class CelebrationsService {
  constructor(
    private readonly repository: CelebrationsRepository,
    private readonly auditService: AuditService,
    private readonly prisma: PrismaService,
  ) {}

  async findAll(organizationId: string, celebrationType?: string, fromDate?: string, toDate?: string) {
    const from = fromDate ? new Date(fromDate) : undefined;
    const to = toDate ? new Date(toDate) : undefined;
    return this.repository.findAll(organizationId, celebrationType, from, to);
  }

  async findById(organizationId: string, id: string) {
    const celebration = await this.repository.findById(organizationId, id);
    if (!celebration) {
      throw new NotFoundException(`Celebration with ID ${id} not found`);
    }
    return celebration;
  }

  async create(
    organizationId: string,
    data: any,
    userId: string,
    ipAddress?: string,
    userAgent?: string,
  ) {
    const celebration = await this.repository.create(organizationId, {
      employeeId: data.employeeId,
      celebrationType: data.celebrationType,
      eventDate: new Date(data.eventDate),
      title: data.title,
      message: data.message,
      yearsCount: data.yearsCount,
      visibility: data.visibility || 'ORGANIZATION',
      isAutoGenerated: false,
    });

    await this.auditService.log({
      action: AuditAction.CELEBRATION_CREATE,
      entityType: 'Celebration',
      entityId: celebration.id,
      organizationId,
      actorUserId: userId,
      details: {
        employeeId: data.employeeId,
        celebrationType: data.celebrationType,
        title: data.title,
      },
      ipAddress,
      userAgent,
    });

    return celebration;
  }

  async wish(organizationId: string, id: string) {
    await this.findById(organizationId, id);
    return this.repository.incrementWishes(organizationId, id);
  }

  async syncCelebrations(
    organizationId: string,
    targetYear?: number,
    userId?: string,
    ipAddress?: string,
    userAgent?: string,
  ) {
    const year = targetYear || new Date().getFullYear();

    const employees = await this.prisma.employee.findMany({
      where: {
        organizationId,
        status: 'ACTIVE',
      },
      select: {
        id: true,
        firstName: true,
        lastName: true,
        dateOfBirth: true,
        dateOfJoining: true,
      },
    });

    let birthdaysCreated = 0;
    let anniversariesCreated = 0;

    for (const emp of employees) {
      // 1. Birthday sync
      if (emp.dateOfBirth) {
        const dob = new Date(emp.dateOfBirth);
        const bdayDate = new Date(year, dob.getMonth(), dob.getDate());

        const existingBday = await this.repository.findExistingCelebration(
          organizationId,
          emp.id,
          'BIRTHDAY',
          year,
        );

        if (!existingBday) {
          await this.repository.create(organizationId, {
            employeeId: emp.id,
            celebrationType: 'BIRTHDAY',
            eventDate: bdayDate,
            title: `Happy Birthday, ${emp.firstName}! 🎂`,
            message: `Wishing ${emp.firstName} a very happy birthday and an extraordinary year ahead!`,
            visibility: 'ORGANIZATION',
            isAutoGenerated: true,
          });
          birthdaysCreated++;
        }
      }

      // 2. Work Anniversary sync
      if (emp.dateOfJoining) {
        const doj = new Date(emp.dateOfJoining);
        const years = year - doj.getFullYear();

        if (years >= 1) {
          const annivDate = new Date(year, doj.getMonth(), doj.getDate());

          const existingAnniv = await this.repository.findExistingCelebration(
            organizationId,
            emp.id,
            'WORK_ANNIVERSARY',
            year,
          );

          if (!existingAnniv) {
            const suffix =
              years === 1
                ? '1st'
                : years === 2
                ? '2nd'
                : years === 3
                ? '3rd'
                : `${years}th`;

            await this.repository.create(organizationId, {
              employeeId: emp.id,
              celebrationType: 'WORK_ANNIVERSARY',
              eventDate: annivDate,
              title: `Happy ${suffix} Work Anniversary, ${emp.firstName}! 🎉`,
              message: `Congratulations to ${emp.firstName} on completing ${years} year${
                years > 1 ? 's' : ''
              } with the team!`,
              yearsCount: years,
              visibility: 'ORGANIZATION',
              isAutoGenerated: true,
            });
            anniversariesCreated++;
          }
        }
      }
    }

    if (userId) {
      await this.auditService.log({
        action: AuditAction.CELEBRATION_SYNC,
        entityType: 'Celebration',
        entityId: organizationId,
        organizationId,
        actorUserId: userId,
        details: { year, birthdaysCreated, anniversariesCreated },
        ipAddress,
        userAgent,
      });
    }

    return {
      year,
      birthdaysCreated,
      anniversariesCreated,
      totalCreated: birthdaysCreated + anniversariesCreated,
    };
  }
}
